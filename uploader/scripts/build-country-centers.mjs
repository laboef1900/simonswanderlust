#!/usr/bin/env node
/**
 * One-off generator for `public/country-centers.js`.
 *
 * Fetches Natural Earth's 1:50m admin-0 countries (pinned release v5.1.2) and
 * keeps, per country, its ISO 3166-1 alpha-2 code, its label point, and the
 * German/English names the dataset carries. Run it only to refresh the asset:
 *
 *   node scripts/build-country-centers.mjs [--out public/country-centers.js]
 *
 * WHY the label point (LABEL_Y/LABEL_X) and not a centroid: Natural Earth
 * places it inside the country's main landmass, so France lands in France
 * rather than being dragged towards its overseas departments. The editor uses
 * it as an approximate story location that the author can refine.
 *
 * WHY a committed asset: the editor resolves coordinates offline, in the
 * browser, with no runtime third-party request and no dependency.
 *
 * @ai-warning Do NOT hand-edit the generated module. Every coordinate claims
 * to come from Natural Earth; an edited value is an invented location with a
 * citation attached to it. Add names by changing the rules below, not by hand.
 */

import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

/**
 * Natural Earth 1:50m "Admin 0 – Countries", via the natural-earth-vector
 * mirror at a release tag. Public domain
 * (https://www.naturalearthdata.com/about/terms-of-use/): no attribution
 * required; the generated file credits it anyway.
 */
const RELEASE = 'v5.1.2';
const SOURCE = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${RELEASE}/geojson/ne_50m_admin_0_countries.geojson`;
const NAME_FIELDS = ['NAME', 'NAME_LONG', 'ADMIN', 'FORMAL_EN', 'NAME_EN', 'NAME_DE', 'NAME_ALT', 'NAME_CIAWF'];

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const out = resolve(outIndex >= 0 ? args[outIndex + 1] : 'public/country-centers.js');

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) throw new Error(`Natural Earth download failed: ${response.status}`);
const features = (await response.json()).features.map((feature) => feature.properties);

// ISO_A2_EH fills the codes ISO_A2 leaves as -99 (France, Norway, Kosovo).
// Rows without any two-letter code (Somaliland, N. Cyprus, Siachen) cannot be
// written to the ISO field and are dropped. When several rows share a code
// (Australia and two dependencies), the most populous one is the country.
const byCode = new Map();
for (const p of features) {
  const code = p.ISO_A2_EH;
  if (!/^[A-Z]{2}$/.test(code)) continue;
  const kept = byCode.get(code);
  if (!kept || p.POP_EST > kept.POP_EST) byCode.set(code, p);
}

// Dotted initialisms (U.S.A., U.K., D.R.C.) are names people type; one that
// spells ANOTHER country's ISO code (S.K. vs Slovakia, B.H. vs Bahrain) is not
// trustworthy and is left out.
function initialism(p, code) {
  if (typeof p.ABBREV !== 'string' || !/^([A-Z]\.){2,}$/.test(p.ABBREV)) return [];
  const letters = p.ABBREV.replace(/\./g, '');
  return letters.length === 2 && letters !== code && byCode.has(letters) ? [] : [p.ABBREV];
}

const round = (value) => Math.round(value * 10000) / 10000;
const rows = [...byCode.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, p]) => {
    const names = [...new Set([
      ...NAME_FIELDS.map((field) => p[field]).filter((name) => typeof name === 'string' && name.trim()),
      ...initialism(p, code),
    ])];
    if (!Number.isFinite(p.LABEL_Y) || !Number.isFinite(p.LABEL_X)) throw new Error(`no label point for ${code}`);
    if (Math.abs(p.LABEL_Y) > 90 || Math.abs(p.LABEL_X) > 180) throw new Error(`label point out of range for ${code}`);
    return [code, round(p.LABEL_Y), round(p.LABEL_X), ...names];
  });

const body = rows.map((row) => '    ' + JSON.stringify(row) + ',').join('\n');
await writeFile(out, `/* Generated by scripts/build-country-centers.mjs — do not edit by hand.
 * Approximate country centres (label points) and names from Natural Earth
 * 1:50m Admin 0 – Countries, ${RELEASE}. Made with Natural Earth; public domain:
 * https://www.naturalearthdata.com/about/terms-of-use/
 * Row: [ISO 3166-1 alpha-2, latitude, longitude, ...names (EN/DE/alternates)]
 */
(function (root) {
  'use strict';
  root.CountryCenters = [
${body}
  ];
})(typeof window !== 'undefined' ? window : globalThis);
`);
console.log(`wrote ${rows.length} countries to ${out}`);
