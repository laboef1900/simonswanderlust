import { afterEach, describe, expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

interface Refresh {
  start(initial?: boolean): void; stop(): void; refresh(trigger?: string): Promise<void>;
  beginAction(): number; endAction(refreshAfter?: boolean): void; accept(value: unknown, version?: number): void; invalidate(): void;
}
function surface(read: (signal: AbortSignal, publish: (value: unknown) => void) => Promise<unknown>, resource?: () => string) {
  const window = new EventTarget();
  const document = Object.assign(new EventTarget(), { hidden: false });
  const apply = vi.fn(), unavailable = vi.fn(), unauthorized = vi.fn();
  const context = vm.createContext({ window, document, AbortController, Date, setTimeout, clearTimeout });
  vm.runInContext(readFileSync('public/publication-refresh.js', 'utf8'), context);
  const api = (window as EventTarget & { PublicationRefresh: { create(options: unknown): Refresh } }).PublicationRefresh;
  const refresh = api.create({ read, resource, apply, unavailable, unauthorized });
  return { refresh, window, document, apply, unavailable, unauthorized };
}
afterEach(() => { vi.useRealTimers(); });

describe('read-only publication observation bounds', () => {
  it('observes external rebuilds within 30 seconds even after Live; pauses while hidden and coalesces focus/visibility', async () => {
    vi.useFakeTimers();
    const read = vi.fn(async () => 'live');
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    read.mockResolvedValue('draft still live');
    await vi.advanceTimersByTimeAsync(30000);
    expect(s.apply).toHaveBeenLastCalledWith('draft still live');
    expect(read).toHaveBeenCalledTimes(2);
    s.document.hidden = true;
    s.document.dispatchEvent(new Event('visibilitychange'));
    await vi.advanceTimersByTimeAsync(120000);
    expect(read).toHaveBeenCalledTimes(2);
    s.document.hidden = false;
    s.document.dispatchEvent(new Event('visibilitychange'));
    s.window.dispatchEvent(new Event('focus'));
    await vi.advanceTimersByTimeAsync(0);
    expect(read).toHaveBeenCalledTimes(3);
    s.window.dispatchEvent(new Event('focus'));
    await vi.advanceTimersByTimeAsync(4999);
    expect(read).toHaveBeenCalledTimes(3);
    await vi.advanceTimersByTimeAsync(1);
    s.window.dispatchEvent(new Event('focus'));
    await vi.advanceTimersByTimeAsync(0);
    expect(read).toHaveBeenCalledTimes(4);
    s.refresh.stop();
  });
  it.each([false, true])('resumes fresh observations after cached navigation, discarding pre-navigation reads (settled=%s)', async (settled) => {
    vi.useFakeTimers();
    const old = Promise.withResolvers<unknown>();
    const read = vi.fn().mockImplementationOnce(() => old.promise).mockResolvedValue('after return');
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    s.window.dispatchEvent(Object.assign(new Event('pagehide'), { persisted: true }));
    if (settled) await vi.advanceTimersByTimeAsync(90000);
    expect(read).toHaveBeenCalledTimes(1);
    s.window.dispatchEvent(Object.assign(new Event('pageshow'), { persisted: true }));
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply).toHaveBeenLastCalledWith('after return');
    expect(read).toHaveBeenCalledTimes(2);
    old.resolve('before navigation');
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['after return']);
    await s.refresh.refresh();
    expect(read).toHaveBeenCalledTimes(3);
    await vi.advanceTimersByTimeAsync(30000);
    expect(read).toHaveBeenCalledTimes(4);
    s.refresh.stop();
  });
  it('does not revive an explicitly stopped controller on cached-page restoration', async () => {
    vi.useFakeTimers();
    const read = vi.fn(async () => 'live');
    const s = surface(read);
    s.refresh.start(false);
    s.window.dispatchEvent(Object.assign(new Event('pagehide'), { persisted: true }));
    s.refresh.stop();
    s.window.dispatchEvent(Object.assign(new Event('pageshow'), { persisted: true }));
    await vi.advanceTimersByTimeAsync(30000);
    expect(read).not.toHaveBeenCalled();
  });
  it('bounds a hung read to ten seconds, discards its late Live, and has no catch-up queue', async () => {
    vi.useFakeTimers();
    const pending = Promise.withResolvers<unknown>();
    const read = vi.fn(() => pending.promise);
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    s.window.dispatchEvent(new Event('focus'));
    s.refresh.refresh();
    expect(read).toHaveBeenCalledTimes(1);
    await vi.advanceTimersByTimeAsync(10000);
    expect(s.unavailable).toHaveBeenCalledTimes(1);
    pending.resolve('stale live');
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply).not.toHaveBeenCalled();
    expect(read).toHaveBeenCalledTimes(1);
    s.refresh.stop();
  });
  it('rejects pre-action reads, renders the receipt projection, then reads once without write replay', async () => {
    vi.useFakeTimers();
    const old = Promise.withResolvers<unknown>();
    const read = vi.fn().mockImplementationOnce(() => old.promise).mockResolvedValue('fresh draft');
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    s.refresh.beginAction();
    await vi.advanceTimersByTimeAsync(60000);
    s.window.dispatchEvent(new Event('focus'));
    expect(read).toHaveBeenCalledTimes(1);
    s.refresh.accept('acknowledged draft');
    expect(s.apply).toHaveBeenLastCalledWith('acknowledged draft');
    s.refresh.endAction();
    old.resolve('old live');
    await vi.advanceTimersByTimeAsync(0);
    expect(read).toHaveBeenCalledTimes(2);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['acknowledged draft', 'fresh draft']);
    s.refresh.stop();
  });
  it('reuses an item observation without a trailing read, including nested actions and an aborted active read', async () => {
    vi.useFakeTimers();
    const old = Promise.withResolvers<unknown>();
    const read = vi.fn().mockImplementationOnce(() => old.promise).mockResolvedValue('later external change');
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    s.refresh.beginAction();
    const version = s.refresh.beginAction();
    s.refresh.accept('item recovery observation', version);
    s.refresh.endAction(false);
    s.refresh.endAction(false);
    old.resolve('old projection');
    await vi.advanceTimersByTimeAsync(0);
    expect(read).toHaveBeenCalledTimes(1);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['item recovery observation']);
    await vi.advanceTimersByTimeAsync(30000);
    expect(read).toHaveBeenCalledTimes(2);
    expect(s.apply).toHaveBeenLastCalledWith('later external change');
    s.refresh.stop();
  });
  it('rejects an item observation superseded by another action', async () => {
    vi.useFakeTimers();
    const read = vi.fn(async () => 'background');
    const s = surface(read);
    s.refresh.start(false);
    const oldVersion = s.refresh.beginAction();
    const currentVersion = s.refresh.beginAction();
    s.refresh.accept('current item', currentVersion);
    s.refresh.accept('old item', oldVersion);
    s.refresh.endAction(false);
    s.refresh.endAction(false);
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['current item']);
    expect(read).not.toHaveBeenCalled();
    s.refresh.stop();
  });
  it('retains a nested selection refresh when an older item read settles without requesting another read', async () => {
    vi.useFakeTimers();
    const read = vi.fn(async () => 'selected item');
    const s = surface(read);
    s.refresh.start(false);
    const oldVersion = s.refresh.beginAction();
    s.refresh.beginAction();
    s.refresh.endAction();
    s.refresh.accept('old item', oldVersion);
    s.refresh.endAction(false);
    await vi.advanceTimersByTimeAsync(0);
    expect(read).toHaveBeenCalledTimes(1);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['selected item']);
    s.refresh.stop();
  });
  it('discards a late resource response after selection change', async () => {
    vi.useFakeTimers();
    let selected = 'first';
    const old = Promise.withResolvers<unknown>();
    const s = surface(vi.fn().mockImplementationOnce(() => old.promise).mockResolvedValue('second publication'), () => selected);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    selected = 'second';
    s.refresh.invalidate();
    await vi.advanceTimersByTimeAsync(0);
    await s.refresh.refresh();
    old.resolve('first publication');
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply.mock.calls.map(([value]) => value)).toEqual(['second publication']);
    s.refresh.stop();
  });
  it('marks 401 unavailable, invokes session handling once and stops reads', async () => {
    vi.useFakeTimers();
    const read = vi.fn(async () => { throw Object.assign(new Error('unauthorized'), { status: 401 }); });
    const s = surface(read);
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(0);
    await vi.advanceTimersByTimeAsync(90000);
    expect(s.unavailable).toHaveBeenCalledTimes(1);
    expect(s.unauthorized).toHaveBeenCalledTimes(1);
    expect(read).toHaveBeenCalledTimes(1);
  });
});

describe('independent optional observation deadlines', () => {
  it('retains fresh post facts when optional history stalls, aborts the request, and rejects late progress', async () => {
    vi.useFakeTimers();
    let signal: AbortSignal | undefined;
    let late: ((value: unknown) => void) | undefined;
    const pending = Promise.withResolvers<unknown>();
    const s = surface(async (readSignal, publish) => {
      signal = readSignal;
      late = publish;
      publish('fresh live post; history unavailable');
      return pending.promise;
    });
    s.refresh.start();
    await vi.advanceTimersByTimeAsync(10000);
    expect(signal?.aborted).toBe(true);
    expect(s.apply).toHaveBeenLastCalledWith('fresh live post; history unavailable');
    expect(s.unavailable).not.toHaveBeenCalled();
    late?.('stale history');
    pending.resolve('stale final response');
    await vi.advanceTimersByTimeAsync(0);
    expect(s.apply).toHaveBeenCalledTimes(1);
    s.refresh.stop();
  });
});
